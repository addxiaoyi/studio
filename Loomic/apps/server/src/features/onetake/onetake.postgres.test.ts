import { randomUUID } from "node:crypto";
import { mkdtemp, mkdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { Pool } from "pg";
import { describe, expect, it } from "vitest";
import { createTranscriptEdit, transcriptExportSchema, type Transcript } from "@helstera/shared";
import { createTranscriptStore } from "./store.js";
import { claimTranscriptWork, expireTranscripts, performTranscriptWork } from "./worker.js";

const document: Transcript = { duration: 3, words: [{ text: "测试", start: 0.5, end: 1.5, confidence: 0.9, kind: "normal" }], silences: [{ start: 1.5, end: 2.5 }] };
const exportOptions = transcriptExportSchema.parse({ subtitle: {} });

describe.skipIf(!process.env.HELT_TEST_DATABASE_URL)("OneTake PostgreSQL lifecycle", () => {
  it("binds ownership, source, revision and approval; leases fence late receipts and preserve active exports", async () => {
    const url = new URL(process.env.HELT_TEST_DATABASE_URL!);
    if (!["127.0.0.1", "localhost", "[::1]"].includes(url.hostname)) throw new Error("Only local test PostgreSQL is permitted.");
    const admin = new Pool({ connectionString: url.href });
    const schema = `onetake_test_${randomUUID().replaceAll("-", "")}`;
    await admin.query(`create schema ${schema}`);
    const db = new Pool({ connectionString: url.href, options: `-c search_path=${schema}` });
    const directory = await mkdtemp(join(tmpdir(), "loomic-onetake-test-"));
    try {
      await db.query("create table app_users(id uuid primary key); create table workspaces(id uuid primary key)");
      await db.query(await readFile(new URL("../../local-db/migrations/20261106000002_onetake_jobs.sql", import.meta.url), "utf8"));
      const userId = randomUUID(), workspaceId = randomUUID();
      await db.query("insert into app_users values($1)", [userId]);
      await db.query("insert into workspaces values($1)", [workspaceId]);
      const sourceDir = join(directory, "onetake", "upload-test");
      await mkdir(sourceDir, { recursive: true });
      const source = join(sourceDir, "source.mp4");
      await writeFile(source, "isolated fixture");
      const store = createTranscriptStore(db);
      const input = { userId, workspaceId, key: randomUUID(), name: "source.mp4", path: source, digest: "a".repeat(64), mime: "video/mp4", model: "tiny", language: "zh" };
      const created = await Promise.all([store.create(input), store.create(input)]);
      expect(created[0]!.task.id).toBe(created[1]!.task.id);
      expect(created.filter(item => item.created)).toHaveLength(1);
      const id = created[0]!.task.id;
      await expect(store.owned(randomUUID(), id)).rejects.toThrow();
      await expect(store.create({ ...input, digest: "b".repeat(64) })).rejects.toThrow();
      const claims = await Promise.all([claimTranscriptWork(db), claimTranscriptWork(db)]);
      expect(claims.filter(Boolean)).toHaveLength(1);
      const first = claims.find(Boolean)!;
      await db.query("update video_transcripts set lease_until=now()-interval '1 second' where id=$1", [id]);
      const resumed = (await claimTranscriptWork(db))!;
      expect(resumed.token).not.toBe(first.token);
      await performTranscriptWork(db, first, async () => document);
      expect((await store.owned(userId, id)).state).toBe("running");
      await performTranscriptWork(db, resumed, async () => document);
      const edit = createTranscriptEdit(document);
      edit.silences[0] = true;
      const task = await store.saveEdit(userId, id, 0, edit);
      expect(task.revision).toBe(1);
      const summaries = await store.list(userId);
      expect(summaries).toHaveLength(1);
      expect(summaries[0]).not.toHaveProperty("transcript");
      expect(summaries[0]).not.toHaveProperty("edit");
      await expect(store.saveEdit(userId, id, 0, edit)).rejects.toThrow();
      const pending = await store.prepareExport(userId, id, 1, randomUUID(), exportOptions);
      expect(await claimTranscriptWork(db)).toBeNull();
      await expect(store.confirmExport(userId, pending.id, "b".repeat(64))).rejects.toThrow();
      await expect(store.confirmExport(randomUUID(), pending.id, pending.fingerprint)).rejects.toThrow();
      await db.query("update video_transcript_exports set expires_at=now()-interval '1 second' where id=$1", [pending.id]);
      await expect(store.confirmExport(userId, pending.id, pending.fingerprint)).rejects.toThrow();
      const approved = await store.prepareExport(userId, id, 1, randomUUID(), exportOptions);
      await Promise.all([store.confirmExport(userId, approved.id, approved.fingerprint), store.confirmExport(userId, approved.id, approved.fingerprint)]);
      const exports = await Promise.all([claimTranscriptWork(db), claimTranscriptWork(db)]);
      expect(exports.filter(Boolean)).toHaveLength(1);
      const active = exports.find(Boolean)!;
      await store.cancelExport(userId, approved.id);
      await performTranscriptWork(db, active, async request => { await writeFile(String(request.output), "late export"); return {}; });
      expect((await store.exported(userId, approved.id)).state).toBe("canceled");
      const final = await store.prepareExport(userId, id, 1, randomUUID(), exportOptions);
      await store.confirmExport(userId, final.id, final.fingerprint);
      const leased = (await claimTranscriptWork(db))!;
      await db.query("update video_transcripts set expires_at=now()-interval '1 second' where id=$1", [id]);
      await expireTranscripts(db, directory);
      expect((await stat(source)).isFile()).toBe(true);
      await performTranscriptWork(db, leased, async request => { await writeFile(String(request.output), "completed fixture"); return {}; });
      await expireTranscripts(db, directory);
      await expect(stat(source)).rejects.toMatchObject({ code: "ENOENT" });
      const expired = (await db.query("select state,cleaned_at from video_transcripts where id=$1", [id])).rows[0];
      expect(expired.state).toBe("expired");
      expect(expired.cleaned_at).toBeInstanceOf(Date);
      await expireTranscripts(db, directory);
      expect(await claimTranscriptWork(db)).toBeNull();
    } finally {
      await db.end();
      await admin.query(`drop schema ${schema} cascade`);
      await admin.end();
      await rm(directory, { recursive: true, force: true });
    }
  });
});
