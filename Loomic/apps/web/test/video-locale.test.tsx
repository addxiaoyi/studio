import "@testing-library/jest-dom/vitest";
import { cleanup, render, screen, act } from "@testing-library/react";
import { afterEach, expect, it, vi } from "vitest";
import { StudioAiEditorPanel } from "@/components/studio-ai-editor-panel";
import { setStoredLocale } from "@/lib/i18n";
import { installStudioChinese } from "../../../scripts/visualforge/studio-i18n";
afterEach(() => { cleanup(); vi.unstubAllGlobals(); });
it("switches AI controls and dynamic editor labels without altering user input", async () => {
  document.documentElement.lang = "zh-CN";
  const values = new Map<string, string>();
  vi.stubGlobal("localStorage", { getItem: (key: string) => values.get(key) ?? null, setItem: (key: string, value: string) => values.set(key, value) });
  render(<StudioAiEditorPanel runtime={null} token="test" userId="test" mediaRevision={1} exported={vi.fn()} />);
  expect(screen.getByLabelText("描述视频编辑目标")).toBeVisible();
  const host = document.createElement("div");
  host.innerHTML = '<button aria-label="Mute video">Video</button><input value="Video" aria-label="Output name" />';
  document.body.append(host);
  const dispose = installStudioChinese(host);
  expect(host.querySelector("button")?.textContent).toBe("视频");
  expect(host.querySelector("input")?.value).toBe("Video");
  act(() => setStoredLocale("en-US"));
  expect(screen.getByLabelText("Describe your video edit")).toBeVisible();
  expect(host.querySelector("button")?.getAttribute("aria-label")).toBe("Mute video");
  expect(host.querySelector("input")?.getAttribute("aria-label")).toBe("Output name");
  act(() => setStoredLocale("zh-CN"));
  host.querySelector("button")!.setAttribute("aria-label", "Unmute video");
  await act(async () => { await Promise.resolve(); });
  expect(host.querySelector("button")?.getAttribute("aria-label")).toBe("取消静音");
  dispose(); host.remove();
});
