import { expect, test } from "@playwright/test";
import { loadEnvFile } from "node:process";
import { resolve } from "node:path";
import { readFile } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import { createEditorBrowserFixture } from "../../server/src/features/video-editor/browser-fixture";

loadEnvFile(resolve("../../.env.local"));
let fixture: Awaited<ReturnType<typeof createEditorBrowserFixture>>;
test.beforeAll(async () => {
  fixture = await createEditorBrowserFixture(process.env.DATABASE_URL!, "http://localhost:3222", JSON.stringify({ summary: "保留画面并添加标题", actions: [{ type: "caption", text: "新品上市", startMs: 0, endMs: 1000 }] }));
});
test.afterAll(async () => { await fixture?.close(); });

test("one menu guides a confirmed edit through playable export and undo", async ({ page, context }, info) => {
  const errors: string[] = [];page.on("pageerror", error => errors.push(error.message));
  expect((await context.request.post("http://localhost:3311/api/local-auth/password", { data: { email: fixture.email, password: fixture.password } })).status()).toBe(200);
  await page.goto("/video/?/MyComp");
  await expect(page.getByLabel("导入本机素材", { exact: true })).toBeEnabled({ timeout: 90_000 });
  const snapshot = () => page.evaluate(() => (window as any).remotion_browserStudio.loomicSnapshot("MyComp"));
  const before = await snapshot();
  await page.locator("button.__remotion-studio-menu-initiator").filter({ hasText: /^合成$/ }).click();
  await expect(page.getByRole("button", { name: "导出视频…", exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "复制文件位置", exact: true })).toHaveCount(0);
  await expect(page.getByRole("button", { name: "在本站 AI 中批注", exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "AI 修改…", exact: true }).last().click();
  await expect(page.getByLabel("修改对象", { exact: true })).toContainText("MyComp");
  await expect(page.getByLabel("AI 编辑当前合成", { exact: true })).not.toContainText("Composition.tsx");
  await page.getByRole("button", { name: "添加标题", exact: true }).click();
  expect((await snapshot()).revision).toBe(before.revision);
  const planned = page.waitForResponse(response => response.url().endsWith("/api/video/editor/plan"));
  await page.getByRole("button", { name: "预览修改方案", exact: true }).click();
  expect((await planned).status()).toBe(200);
  await expect(page.getByRole("button", { name: "确认并应用修改", exact: true })).toBeDisabled();
  expect((await snapshot()).revision).toBe(before.revision);
  await page.getByTestId("studio-ai-plan").getByRole("checkbox").check();
  await page.getByRole("button", { name: "确认并应用修改", exact: true }).click();
  await expect(page.getByRole("heading", { name: "修改已应用", exact: true })).toBeVisible();
  await expect.poll(async () => (await snapshot()).captions.some((caption: {text:string}) => caption.text === "新品上市")).toBe(true);
  await expect(page.getByRole("button", { name: "撤销本次修改", exact: true })).toBeEnabled();
  await page.screenshot({ path: info.outputPath("applied.png") });
  await page.getByTestId("studio-ai-plan").getByRole("button", { name: "导出视频", exact: true }).click();
  const dialog = page.locator("dialog[open]");await expect(dialog).toBeVisible();
  await dialog.getByRole("button", { name: "视频", exact: true }).click();
  await dialog.getByRole("button", { name: "容器", exact: true }).click();
  await dialog.getByText("WebM", { exact: true }).click();
  const downloaded = page.waitForEvent("download", { timeout: 90_000 });
  await dialog.getByRole("button", { name: /渲染.*视频/ }).click();
  const file = info.outputPath("creator-flow.webm");await (await downloaded).saveAs(file);
  expect((await readFile(file)).length).toBeGreaterThan(1000);
  const ffmpeg = process.platform === "win32" ? resolve("../desktop/resources/ffmpeg/win-x64/ffmpeg.exe") : "ffmpeg";
  execFileSync(ffmpeg, ["-v", "error", "-xerror", "-i", file, "-f", "null", "-"], { timeout: 30_000 });
  const savedVideo = page.getByLabel("本机导出记录", { exact: true }).locator("video");
  await expect(savedVideo).toBeVisible();
  await expect.poll(() => savedVideo.evaluate((video: HTMLVideoElement) => video.duration)).toBeCloseTo(2, 1);
  await page.screenshot({ path: info.outputPath("exported.png") });
  await page.getByRole("button", { name: "撤销本次修改", exact: true }).click();
  await expect.poll(async () => (await snapshot()).revision).toBe(before.revision);
  await expect(page.getByText("已撤销本次修改，可以调整要求后重新预览方案。", { exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});
