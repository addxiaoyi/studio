import { test,expect,_electron,type ElectronApplication } from "@playwright/test";
import { randomUUID } from "node:crypto";
import { mkdtemp,rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { websiteWorkflow } from "@helstera/shared";
import { CanvasWorkflowService } from "../../server/src/features/canvas-workflows/service";
import { createWorkflowFixture } from "../../server/src/features/canvas-workflows/browser-fixture";
import { projectWorkflow } from "../src/components/workflow/scene";

test("node workbench inserts on a wire, executes only ancestors and shows private results",async({page},info)=>{
  const fixture=await createWorkflowFixture(process.env.DATABASE_URL!,"http://localhost:3228");
  const folder=await mkdtemp(join(tmpdir(),"workflow-workbench-"));let desktop:ElectronApplication|undefined;
  try{
    const graph=websiteWorkflow(true);graph.nodes[0]!.config={kind:"url",url:"https://example.com"};
    const service=new CanvasWorkflowService(fixture.db),flow=await service.create(fixture.userId,fixture.canvasId,graph,randomUUID());
    await fixture.db.query("update canvases set content=$2::jsonb where id=$1",[fixture.canvasId,JSON.stringify({elements:projectWorkflow([],flow.id,graph,{},false),appState:{scrollX:0,scrollY:0,zoom:{value:1}},files:{}})]);
    if(process.env.HELT_TEST_CANDIDATE_PATH){const env={...process.env,HELSTERA_ISOLATED_TEST:"1",HELSTERA_TEST_USER_DATA:folder,HELSTERA_DESKTOP_LOCAL_URL:"http://localhost:3228"};delete env.ELECTRON_RUN_AS_NODE;desktop=await _electron.launch({executablePath:process.env.HELT_TEST_CANDIDATE_PATH,env:env as Record<string,string>,timeout:45000});page=await desktop.firstWindow();}
    await page.setViewportSize({width:1700,height:1000});
    page.on("pageerror",error=>console.error("[node-workbench-page]",error.message,error.stack));
    page.on("console",message=>{if(message.type()==="error"&&/Route error:|TypeError:|ReferenceError:/.test(message.text()))console.error("[node-workbench-console]",message.text());});
    await page.goto(`http://localhost:3228/${desktop?"desktop-app/":""}canvas/?id=${fixture.canvasId}&session=${fixture.sessionId}`);
    await page.getByRole("button",{name:"打开可视化工作流",exact:true}).click();
    const dock=page.getByRole("region",{name:"可视化工作流",exact:true});
    await dock.getByRole("button",{name:"定位流程节点",exact:true}).click();
    await dock.getByRole("button",{name:"收起流程面板",exact:true}).click();
    const edge=graph.edges.find(edge=>edge.target==="deliver")!;
    const wire=page.locator(`[data-workflow-edge="${edge.id}"]`);
    await expect(wire).toBeAttached();
    const midpoint=await wire.evaluate((el:SVGPathElement)=>{const at=el.getPointAtLength(el.getTotalLength()/2);const matrix=el.getScreenCTM()!;return {x:at.x*matrix.a+matrix.e,y:at.y*matrix.d+matrix.f};});
    await page.mouse.click(midpoint.x,midpoint.y);
    await page.getByRole("button",{name:"插入节点",exact:true}).click();
    const picker=page.getByRole("dialog",{name:"添加处理节点",exact:true});
    await expect(picker.getByRole("button",{name:/网址输入/})).toBeDisabled();
    await picker.getByRole("button",{name:/视频裁剪/}).click();
    await expect(dock.getByRole("textbox",{name:"节点名称",exact:true})).toHaveValue("视频裁剪");
    await dock.getByRole("button",{name:"保存草稿",exact:true}).click();
    await expect(dock.getByRole("button",{name:"已保存",exact:true})).toBeDisabled();
    const saved=await service.get(fixture.userId,fixture.canvasId,flow.id),trim=saved.graph.nodes.find(node=>node.config.kind==="trim")!;
    expect(saved.graph.edges.map(edge=>[edge.source,edge.target])).toEqual([["site","capture"],["capture",trim.id],[trim.id,"deliver"]]);
    await dock.getByRole("button",{name:/浏览与录制 录制网站/}).click();
    await dock.getByRole("button",{name:"输入",exact:true}).click();
    await expect(dock.getByRole("region",{name:"节点输入",exact:true})).toContainText("https://example.com");
    await dock.getByRole("button",{name:"展开节点详情",exact:true}).click();
    const detail=page.getByRole("dialog",{name:"录制网站",exact:true});
    await expect(detail.getByRole("region",{name:"节点参数",exact:true})).toBeVisible();
    await expect(detail.getByRole("region",{name:"节点输出",exact:true})).toContainText("尚无结果");
    await page.screenshot({path:info.outputPath("node-three-pane.png")});
    await detail.getByRole("button",{name:"执行到此节点",exact:true}).click();
    const confirm=page.getByRole("dialog",{name:"执行到「录制网站」",exact:true});
    await expect(confirm).toContainText("上游会重新执行");
    expect((await fixture.db.query("select count(*)::int as n from agent_goals")).rows[0].n).toBe(0);
    await confirm.getByRole("button",{name:"确认运行已保存版本",exact:true}).click();
    await expect(dock.getByRole("region",{name:"工作流运行记录",exact:true})).toContainText("等待动作确认");
    expect((await fixture.db.query("select count(*)::int as n from website_capture_tasks")).rows[0].n).toBe(0);
    await dock.getByRole("button",{name:"需处理",exact:true}).click();
    await dock.getByRole("button",{name:"确认此动作",exact:true}).click();
    await expect(dock.getByRole("region",{name:"工作流运行记录",exact:true})).toContainText("全部完成",{timeout:30000});
    const steps=(await fixture.db.query("select step_id,state from agent_goal_steps order by ordinal")).rows;
    expect(steps.map(step=>step.step_id)).toEqual(["capture","preview-output"]);
    expect(steps.every(step=>step.state==="succeeded")).toBe(true);
    await dock.getByRole("button",{name:"已完成",exact:true}).click();
    await dock.getByRole("button",{name:"定位节点：录制网站",exact:true}).click();
    await dock.getByRole("button",{name:"输出",exact:true}).click();
    await expect(dock.getByRole("region",{name:"节点输出",exact:true})).toContainText("可视化工作流验收");
    await expect(dock.getByRole("region",{name:"节点输出",exact:true}).locator("img")).toBeVisible();
    await page.reload();
    await page.getByRole("button",{name:"打开可视化工作流",exact:true}).click();
    await dock.getByRole("button",{name:/浏览与录制 录制网站/}).click();
    await dock.getByRole("button",{name:"展开节点详情",exact:true}).click();
    await expect(detail.getByRole("region",{name:"节点输出",exact:true})).toContainText("可视化工作流验收");
    await page.setViewportSize({width:760,height:900});
    await expect(detail).toBeInViewport();
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
    await page.screenshot({path:info.outputPath("node-private-result-narrow.png")});
  }finally{await desktop?.close();await fixture.close();await rm(folder,{recursive:true,force:true});}
});
