export const desktopCopyTables: { "zh-CN": DesktopCopy; "en-US": DeepPartial<DesktopCopy> } = {
  "zh-CN": zhCN,
  "en-US": enUS,
};

function isPlainObject(value: unknown): value is Record<string, unknown> {
  return Boolean(value) && typeof value === "object" && !Array.isArray(value);
}

const warnedKeys = new Set<string>();

/**
 * 缺键不是「返回 key 让用户看到 mcp.heading」，而是退回中文原文并留一条告警：
 * 界面宁可回到已知可读的文案，也不该把内部键名当界面文字。
 */
function warnMissing(locale: DesktopLocale, path: string): void {
  const signature = `${locale}:${path}`;
  if (warnedKeys.has(signature)) return;
  warnedKeys.add(signature);
  console.warn(`[desktop-copy] missing "${locale}" copy for "${path}", falling back to zh-CN.`);
}

/** 递归合并：en-US 缺键、空串或结构缺失时逐层回退到中文表。 */
function mergeCopy(
  base: Record<string, unknown>,
  override: unknown,
  path: string,
  locale: DesktopLocale,
): Record<string, unknown> {
  const merged: Record<string, unknown> = {};
  for (const [key, baseValue] of Object.entries(base)) {
    const nextPath = path ? `${path}.${key}` : key;
    const overrideValue = isPlainObject(override) ? override[key] : undefined;
    if (isPlainObject(baseValue)) {
      merged[key] = mergeCopy(baseValue, overrideValue, nextPath, locale);
      continue;
    }
    if (typeof overrideValue === "string" && overrideValue.trim().length > 0) {
      merged[key] = overrideValue;
      continue;
    }
    warnMissing(locale, nextPath);
    merged[key] = baseValue;
  }
  return merged;
}

let enCache: DesktopCopy | null = null;

/** 用覆盖表生成完整副本：缺键/空串回退中文并告警，调用方永远拿到可渲染的字符串。 */
export function mergeDesktopCopy(override: DesktopCopyOverride): DesktopCopy {
  return mergeCopy(zhCN, override, "", "en-US") as DesktopCopy;
}

export function getDesktopCopy(locale?: DesktopLocale | string | null): DesktopCopy {
  if (locale !== "en-US") return zhCN;
  if (!enCache) enCache = mergeDesktopCopy(enUS);
  return enCache;
}

/** `{token}` 占位符替换，复制表保持纯字符串，便于逐键校验。 */
export function formatDesktopCopy(
  template: string,
  values: Record<string, string | number> = {},
): string {
  return template.replace(/\{(\w+)\}/g, (match, token: string) => {
    const value = values[token];
    return value === undefined ? match : String(value);
  });
}

/**
 * 语言来源：显式 prop > 文档声明的 lang。
 *
 * 不直接跟随 navigator.language：桌面壳层与 web 布局都用 <html lang> 显式声明界面
 * 语言，浏览器语言只是系统语言，跟随它会把中文用户切成英文。宿主没有声明 lang 时
 * 维持 zh-CN 默认。
 */
export function resolveDesktopLocale(
  override: DesktopLocale | null | undefined,
  detected: DesktopLocale,
): DesktopLocale {
  if (override === "en-US" || override === "zh-CN") return override;
  const declared = typeof document === "undefined" ? "" : document.documentElement.lang;
  return declared ? detected : "zh-CN";
}

export function useDesktopLocale(override?: DesktopLocale | null): DesktopLocale {
  const detected = useLocale();
  return resolveDesktopLocale(override, detected);
}

export function useDesktopCopy(override?: DesktopLocale | null): {
  locale: DesktopLocale;
  copy: DesktopCopy;
} {
  const locale = useDesktopLocale(override);
  return { locale, copy: getDesktopCopy(locale) };
}
